/**
 * Rebuilds src/data/colleges/logos.ts from whatever crests are sitting in
 * public/colleges/. Run it after adding or removing a PNG there.
 *
 *   npm run logos
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public", "colleges");
const out = path.join(root, "src", "data", "colleges", "logos.ts");

const files = await readdir(dir).catch(() => []);
const slugs = files
  .filter((f) => f.toLowerCase().endsWith(".png"))
  .map((f) => f.slice(0, -4))
  .sort();

const list = slugs.length ? `\n${slugs.map((s) => `  ${JSON.stringify(s)},`).join("\n")}\n` : "";

await writeFile(
  out,
  `/**
 * Colleges that have a real crest in public/colleges/.
 *
 * The badge falls back to the drawn monogram for everything not listed here,
 * so this file can stay empty and the explorer still shows an icon for all of
 * them. To add a crest: save a square PNG (256px is plenty) as
 * public/colleges/<slug>.png, then run \`npm run logos\` to rebuild this list.
 * Use only an image the institute publishes for this purpose.
 *
 * Generated by scripts/sync-college-logos.mjs. Do not edit by hand.
 */
export const collegeLogos = new Set<string>([${list}]);
`,
  "utf8",
);

console.log(`logos.ts written with ${slugs.length} crest${slugs.length === 1 ? "" : "s"}`);
